    /**
     * @param  list<string>  $without
     * @param  list<string>  $with
     * @param  list<string>  $notes
     * @return array{
     *     label: string,
     *     profile: bool,
     *     profile_label: string,
     *     description: string,
     *     without_agreement: list<string>,
     *     with_agreement: list<string>,
     *     notes: list<string>
     * }
     */
    private static function row(
        string $label,
        bool $profile,
        ?string $intro,
        array $without = [],
        array $with = [],
        array $notes = [],
    ): array {
        return [
            'label' => $label,
            'profile' => $profile,
            'profile_label' => $profile ? 'Профильная' : 'Непрофильная',
            'description' => self::formatDescription($intro, $without, $with, $notes),
            'without_agreement' => $without,
            'with_agreement' => $with,
            'notes' => $notes,
        ];
    }

    /**
     * @param  list<string>  $without
     * @param  list<string>  $with
     * @param  list<string>  $notes
     */
    private static function formatDescription(?string $intro, array $without, array $with, array $notes): string
    {
        $parts = [];

        if ($intro !== null && trim($intro) !== '') {
            $parts[] = trim($intro);
        }

        if ($without !== []) {
            $parts[] = "Без согласования с филиалом:\n".self::formatList($without);
        }

        if ($with !== []) {
            $parts[] = "По согласованию с филиалом:\n".self::formatList($with);
        }

        if ($notes !== []) {
            $parts[] = "Примечания:\n".self::formatList($notes);
        }

        return self::normalizeDescriptionText(trim(implode("\n\n", $parts)));
    }

    /** Убирает пробелы/табы в начале каждой строки (для отображения в таблице). */
    public static function normalizeDescriptionText(string $text): string
    {
        $text = trim($text);
        if ($text === '') {
            return '';
        }

        $lines = preg_split("/\r\n|\r|\n/", $text) ?: [];

        return implode("\n", array_map(
            static fn (string $line) => ltrim($line, " \t\u{00A0}\u{FEFF}"),
            $lines
        ));
    }

    /** @param  list<string>  $items */
    private static function formatList(array $items): string
    {
        $lines = [];
        $n = 1;

        foreach ($items as $item) {
            $item = ltrim(trim($item));
            if ($item === '') {
                continue;
            }

            if (preg_match('/^\d+\.\s/u', $item)) {
                $lines[] = $item;
            } else {
                $lines[] = $n.'. '.$item;
                $n++;
            }
        }

        return implode("\n", $lines);
    }

    /**
     * @return array{
     *     label: string,
     *     profile: bool,
     *     profile_label: string,
     *     description: string,
     *     without_agreement: list<string>,
     *     with_agreement: list<string>,
     *     notes: list<string>
     * }|null
     */
    public static function get(string $code): ?array
    {
        return self::definitions()[$code] ?? null;
    }
}
